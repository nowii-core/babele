# Generato da Babele

def main():
    saluto = "Ciao, mondo!"
    print(saluto)
    x = (40 + 2)
    print(x)
    n = 10
    somma = 0
    i = 1
    while (i < n):
        somma = (somma + i)
        i = (i + 1)
    print(somma)
    if (somma > 50):
        print("Maggiore di 50")
    else:
        print("Minore o uguale a 50")

if __name__ == "__main__":
    main()

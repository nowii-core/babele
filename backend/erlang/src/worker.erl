-module(babele_worker).
-behaviour(gen_server).

-export([start_link/0, compile_file/2, status/0]).
-export([init/1, handle_call/3, handle_cast/2, handle_info/2,
         terminate/2, code_change/3]).

-record(state, {
    id :: integer(),
    tasks_completed = 0 :: non_neg_integer(),
    tasks_failed = 0 :: non_neg_integer(),
    current_task = undefined :: undefined | binary(),
    start_time :: integer()
}).

start_link() ->
    gen_server:start_link(?MODULE, [], []).

compile_file(Pid, FilePath) ->
    gen_server:call(Pid, {compile, FilePath}, 30000).

status() ->
    gen_server:call(?MODULE, status).

init([]) ->
    process_flag(trap_exit, true),
    Id = erlang:unique_integer([positive]),
    StartTime = erlang:system_time(millisecond),
    {ok, #state{
        id = Id,
        start_time = StartTime
    }}.

handle_call({compile, FilePath}, _From, State) ->
    case do_compile(FilePath) of
        {ok, Output} ->
            NewState = State#state{
                tasks_completed = State#state.tasks_completed + 1,
                current_task = undefined
            },
            {reply, {ok, Output}, NewState};
        {error, Reason} ->
            NewState = State#state{
                tasks_failed = State#state.tasks_failed + 1,
                current_task = undefined
            },
            {reply, {error, Reason}, NewState}
    end;

handle_call(status, _From, State) ->
    Uptime = erlang:system_time(millisecond) - State#state.start_time,
    Reply = #{
        worker_id => State#state.id,
        completed => State#state.tasks_completed,
        failed => State#state.tasks_failed,
        current_task => State#state.current_task,
        uptime_ms => Uptime
    },
    {reply, Reply, State};

handle_call(_Req, _From, State) ->
    {reply, {error, unknown_request}, State}.

handle_cast({async_compile, FilePath}, State) ->
    case do_compile(FilePath) of
        {ok, _} ->
            {noreply, State#state{
                tasks_completed = State#state.tasks_completed + 1
            }};
        {error, _} ->
            {noreply, State#state{
                tasks_failed = State#state.tasks_failed + 1
            }}
    end;

handle_cast(_Msg, State) ->
    {noreply, State}.

handle_info({'EXIT', _Pid, Reason}, State) ->
    error_logger:warning_msg("Worker ~p received EXIT: ~p~n",
                             [State#state.id, Reason]),
    {noreply, State};

handle_info(_Info, State) ->
    {noreply, State}.

terminate(Reason, State) ->
    error_logger:info_msg("Worker ~p terminating: ~p (completed: ~p)~n",
                          [State#state.id, Reason, State#state.tasks_completed]),
    ok.

code_change(_OldVsn, State, _Extra) ->
    {ok, State}.

do_compile(FilePath) ->
    case file:read_file(FilePath) of
        {ok, Content} ->
            case tokenize(Content) of
                {ok, Tokens} ->
                    case parse(Tokens) of
                        {ok, AST} ->
                            Code = generate_c(AST),
                            {ok, Code};
                        {error, Reason} ->
                            {error, {parse_error, Reason}}
                    end;
                {error, Reason} ->
                    {error, {tokenize_error, Reason}}
            end;
        {error, Reason} ->
            {error, {file_error, Reason}}
    end.

tokenize(Source) ->
    {ok, Source}.

parse(_Tokens) ->
    {ok, []}.

generate_c(_AST) ->
    <<"/* Generated by Babele (Erlang worker) */\n"
      "#include <stdio.h>\n"
      "int main(void) { return 0; }\n">>.
